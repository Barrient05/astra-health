def lista(ids):
    return [{"id": i, **FUENTES[i]} for i in ids if i in FUENTES]


def agrupadas():
    grupos = {t: [] for t in TIPOS}
    for clave, f in FUENTES.items():
        grupos[f["tipo"]].append({"id": clave, **f, "usos": USOS.get(clave, [])})
    return [{"tipo": t, "nombre": TIPOS[t], "fuentes": grupos[t]} for t in TIPOS if grupos[t]]


def markdown():
    lineas = ["# Fuentes de investigación de Órbita Vital", ""]
    for g in agrupadas():
        lineas += [f"## {g['nombre']}", ""]
        for f in g["fuentes"]:
            ref = f"{f['autor']} ({f['anio']}). *{f['titulo']}*."
            if f["url"]:
                ref += f" {f['url']}"
            lineas.append(f"- {ref}")
            lineas.append(f"  - Dato usado: {f['dato']}")
            if f["usos"]:
                lineas.append(f"  - Dónde se usa: {'; '.join(f['usos'])}")
        lineas.append("")
    return "\n".join(lineas)
